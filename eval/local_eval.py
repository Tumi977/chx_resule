"""Local evaluation harness — strictly mirrors official evaluate.py:

  CD(A,B)  = mean min ||a-b||^2 + mean min ||b-a||^2 (Euclidean^2)
  P2S(A,M) = mean min_y on mesh ||a-y||^2 (uses pcu.closest_points_on_mesh)
  Score    = 0.5*mean(cd_score) + 0.5*mean(p2s_score), each clamped(100*(1-pred/noisy),0,100)
  Both metrics computed AFTER unit-sphere normalization w.r.t the GT cloud.

We use ONE OF:
  - validate.txt subset (99 models, predefined) with deterministic σ=0.01 noise.
We need GT mesh path to compute P2S; fortunately validate.txt models all have
a mesh in dataset_train/shapenet/<synset>/<model>/models/model_normalized.obj.
For P2S the mesh must be in the same coord-frame as the GT cloud, which is
the normalized frame in clean.npz (we have center/scale to recover).

The denormalized mesh: model_obj_vertices were originally in the OBJ's local
frame. clean.npz was generated by:
    pts_norm = (pts_obj - center) / scale
So if we keep noisy/clean in this normalized frame, we just need to similarly
transform mesh vertices: v_norm = (v_obj - center) / scale.
"""
from __future__ import annotations
import os
import time
from typing import Dict, List, Tuple

import numpy as np
from scipy.spatial import cKDTree

import point_cloud_utils as pcu

DATA_ROOT = os.environ.get("DATA_ROOT", "/mnt/ssd4t/data/chx/graphics")


def normalize_to_unit_sphere(pc: np.ndarray):
    pc = pc.astype(np.float64)
    center = (pc.max(axis=0) + pc.min(axis=0)) / 2.0
    pcc = pc - center
    scale = float(np.sqrt((pcc ** 2).sum(axis=1).max()))
    if scale < 1e-12:
        return pcc, center, scale
    return pcc / scale, center, scale


def chamfer_distance(pc_a: np.ndarray, pc_b: np.ndarray, normalize: bool = True) -> float:
    a = pc_a.astype(np.float64)
    b = pc_b.astype(np.float64)
    if normalize:
        b, center, scale = normalize_to_unit_sphere(b)
        if scale < 1e-12:
            return 0.0
        a = (a - center) / scale
    tb = cKDTree(b)
    da, _ = tb.query(a, k=1)
    ta = cKDTree(a)
    db, _ = ta.query(b, k=1)
    return float((da ** 2).mean() + (db ** 2).mean())


def point_to_surface_distance(pc: np.ndarray, mesh_v: np.ndarray, mesh_f: np.ndarray, normalize_ref_pc: np.ndarray) -> float:
    pc = pc.astype(np.float64)
    mv = mesh_v.astype(np.float64).copy()
    ref = normalize_ref_pc.astype(np.float64)
    center = (ref.max(axis=0) + ref.min(axis=0)) / 2.0
    refc = ref - center
    scale = float(np.sqrt((refc ** 2).sum(axis=1).max()))
    if scale < 1e-12:
        return 0.0
    pc = (pc - center) / scale
    mv = (mv - center) / scale
    dists, _, _ = pcu.closest_points_on_mesh(pc.astype(np.float32), mv.astype(np.float32), mesh_f.astype(np.int32))
    return float((dists ** 2).mean())


def metric_to_score(val_pred: float, val_noisy: float) -> float:
    if val_noisy < 1e-15:
        return 100.0 if val_pred < 1e-15 else 0.0
    s = 100.0 * (1.0 - val_pred / val_noisy)
    return max(0.0, min(100.0, s))


def load_obj_mesh(path: str) -> Tuple[np.ndarray, np.ndarray]:
    v, f = pcu.load_mesh_vf(path)
    return v.astype(np.float64), f.astype(np.int32)


def find_mesh_path(rel: str) -> str:
    """rel = 'shapenet/<synset>/<model>'. Returns path to model_normalized.obj or empty."""
    p = os.path.join(DATA_ROOT, "dataset_train", rel, "models", "model_normalized.obj")
    return p if os.path.exists(p) else ""


def load_norm_meta(rel: str):
    p = os.path.join(DATA_ROOT, "dataset_train_pc", rel, "clean.npz")
    d = np.load(p)
    return d["center"].astype(np.float64), float(d["scale"])


def evaluate_one(
    rel_path: str,
    pc_noisy: np.ndarray,
    pc_clean: np.ndarray,
    pc_pred: np.ndarray,
) -> Dict[str, float]:
    """rel_path is 'shapenet/<synset>/<model>'. Returns dict of scores.

    pc_clean is expected in NORMALIZED frame (matching clean.npz coords).
    The mesh on disk is in OBJ frame — we transform with the (center, scale)
    stored in clean.npz so all 4 (pred/noisy/clean/mesh) live in the same
    normalized space.
    """
    out = {}
    out["CD_pred"] = chamfer_distance(pc_pred, pc_clean, normalize=True)
    out["CD_noisy"] = chamfer_distance(pc_noisy, pc_clean, normalize=True)
    out["cd_score"] = metric_to_score(out["CD_pred"], out["CD_noisy"])

    mp = find_mesh_path(rel_path)
    if mp:
        v_obj, f = load_obj_mesh(mp)
        center, scale = load_norm_meta(rel_path)
        v_norm = (v_obj - center) / scale  # mesh in normalized frame
        # Both pc_clean and v_norm should now be in unit-sphere-ish space
        out["P2S_pred"] = point_to_surface_distance(pc_pred, v_norm, f, pc_clean)
        out["P2S_noisy"] = point_to_surface_distance(pc_noisy, v_norm, f, pc_clean)
        out["p2s_score"] = metric_to_score(out["P2S_pred"], out["P2S_noisy"])
    else:
        out["P2S_pred"] = float("nan")
        out["P2S_noisy"] = float("nan")
        out["p2s_score"] = float("nan")

    if not np.isnan(out["p2s_score"]):
        out["score"] = 0.5 * out["cd_score"] + 0.5 * out["p2s_score"]
    else:
        out["score"] = out["cd_score"]
    return out


def aggregate(results: List[Dict[str, float]]) -> Dict[str, float]:
    keys = ["CD_pred", "CD_noisy", "cd_score", "P2S_pred", "P2S_noisy", "p2s_score", "score"]
    agg = {}
    for k in keys:
        vals = [r[k] for r in results if not np.isnan(r[k])]
        agg[k] = float(np.mean(vals)) if vals else float("nan")
    agg["n_total"] = len(results)
    agg["n_with_p2s"] = sum(not np.isnan(r["p2s_score"]) for r in results)
    return agg


def fmt_summary(agg: Dict[str, float]) -> str:
    lines = []
    lines.append("=" * 60)
    lines.append("Local validation summary")
    lines.append("=" * 60)
    lines.append(f"  N total          : {agg['n_total']}")
    lines.append(f"  N with P2S       : {agg['n_with_p2s']}")
    lines.append(f"  CD_pred          : {agg['CD_pred']:.8f}")
    lines.append(f"  CD_noisy         : {agg['CD_noisy']:.8f}")
    lines.append(f"  CD_score         : {agg['cd_score']:.2f} / 100")
    lines.append(f"  P2S_pred         : {agg['P2S_pred']:.8f}")
    lines.append(f"  P2S_noisy        : {agg['P2S_noisy']:.8f}")
    lines.append(f"  P2S_score        : {agg['p2s_score']:.2f} / 100")
    lines.append("-" * 60)
    lines.append(f"  Total Score      : {agg['score']:.2f} / 100")
    lines.append("=" * 60)
    return "\n".join(lines)
